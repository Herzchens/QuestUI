import { readFileSync, writeFileSync } from "node:fs";

// Pack authored material pairs into managed CSS. Never combine multiple fracture systems.
const EXPECTED = ["spine", "burst", "edge", "lattice", "rift", "fault", "fork", "caldera", "shatter", "shear", "shell"];

function validateManifest(maps) {
    if (!Array.isArray(maps) || maps.length !== EXPECTED.length) throw new Error("Invalid Obsidian material count");
    for (const [index, map] of maps.entries()) {
        const position = /^(\d+)% (\d+)%$/.exec(map?.position ?? "");
        if (!map || map.name !== EXPECTED[index] || Object.keys(map).sort().join(",") !== "mask,name,position,surface"
            || map.surface !== map.name + "-surface.jpg" || map.mask !== map.name + "-mask.png"
            || !position || position.slice(1).some(value => Number(value) > 100)) {
            throw new Error("Invalid Obsidian material pair at index " + index);
        }
    }
}

function buildMaterialFiles(maps, asset) {
    validateManifest(maps);
    const url = (name, mime) => 'url("data:image/' + mime + ';base64,' + asset(name) + '")';
    const surface = map => url(map.surface, "jpeg");
    const mask = map => url(map.mask, "png");
    const shell = maps.find(map => map.name === "shell");
    const cards = maps.filter(map => map.name !== "shell");
    let css = "/* Generated by generateFractureAssets.mjs. One authored surface and aligned fissure mask per card. */\n"
        + ".quest-ui-theme-obsidian {\n"
        + "    --quest-ui-obsidian-shell-facets: " + surface(shell) + ";\n"
        + "    --quest-ui-obsidian-shell-fissures: " + mask(shell) + ";\n}\n";
    for (const [index, map] of cards.entries()) {
        css += '.quest-ui-theme-obsidian .quest-ui-card[data-obsidian-fracture="' + index + '"] {\n'
            + "    --quest-ui-obsidian-fracture-facets: " + surface(map) + ";\n"
            + "    --quest-ui-obsidian-fracture-lines: " + mask(map) + ";\n"
            + "    --quest-ui-obsidian-core-position: " + map.position + ";\n}\n";
    }
    return {
        "fracture-assets.css": css,
        "fractureVariantCount.ts": "// Generated by generateFractureAssets.mjs. Do not edit directly.\nexport const OBSIDIAN_FRACTURE_VARIANT_COUNT = " + cards.length + ";\n"
    };
}

function readBitmap(name, assets) {
    const bytes = readFileSync(new URL(name, assets));
    let width, height;
    if (name.endsWith(".png")) {
        if (bytes.length < 33 || bytes.subarray(0, 8).toString("hex") !== "89504e470d0a1a0a"
            || bytes.toString("ascii", 12, 16) !== "IHDR" || bytes[25] !== 6) {
            throw new Error("Expected an RGBA PNG mask: " + name);
        }
        width = bytes.readUInt32BE(16);
        height = bytes.readUInt32BE(20);
    } else if (name.endsWith(".jpg")) {
        if (bytes.length < 4 || bytes.readUInt16BE(0) !== 0xffd8) throw new Error("Expected a JPEG surface: " + name);
        for (let offset = 2; offset + 8 < bytes.length;) {
            if (bytes[offset++] !== 0xff) throw new Error("Invalid JPEG marker: " + name);
            while (bytes[offset] === 0xff) offset++;
            const marker = bytes[offset++];
            if ([0xc0, 0xc1, 0xc2, 0xc3, 0xc5, 0xc6, 0xc7, 0xc9, 0xca, 0xcb, 0xcd, 0xce, 0xcf].includes(marker)) {
                height = bytes.readUInt16BE(offset + 3);
                width = bytes.readUInt16BE(offset + 5);
                break;
            }
            const length = bytes.readUInt16BE(offset);
            if (length < 2 || offset + length > bytes.length) throw new Error("Invalid JPEG segment: " + name);
            offset += length;
        }
    }
    if (width !== 1120 || height !== 180) throw new Error("Expected 1120 × 180 material: " + name);
    return bytes.toString("base64");
}

const assets = new URL("./assets/", import.meta.url);
const maps = JSON.parse(readFileSync(new URL("manifest.json", assets), "utf8"));
const generated = buildMaterialFiles(maps, name => readBitmap(name, assets));
for (const [name, content] of Object.entries(generated)) {
    const destination = new URL("./" + name, import.meta.url);
    if (process.argv.includes("--check")) {
        if (readFileSync(destination, "utf8") !== content) throw new Error("Obsidian generated material is out of date: " + name);
    } else {
        writeFileSync(destination, content);
    }
}
if (process.argv.includes("--check")) console.log("Obsidian authored material pairs and variant count: verified");
