// Pack authored material assets into managed CSS. No geometry or image synthesis.
import { readFileSync, writeFileSync } from "node:fs";

function managedCSS(maps,asset){
    const url=(name,mime)=>`url("data:image/${mime};base64,${asset(name)}")`;
    const surface=a=>url(a.surface,"jpeg"),mask=a=>url(a.mask,"png");
    const shell=maps.find(m=>m.name==="shell");
    return `/* Generated by generateFractureAssets.mjs. Authored raster surfaces and aligned reflection masks. */\n.quest-ui-theme-obsidian {\n    --quest-ui-obsidian-shell-facets: ${surface(shell)};\n    --quest-ui-obsidian-shell-fissures: ${mask(shell)};\n}\n${maps.filter(m=>m.name!=="shell").map((a,i)=>`.quest-ui-theme-obsidian .quest-ui-card[data-obsidian-fracture="${i}"] {\n    --quest-ui-obsidian-fracture-facets: ${surface(a)};\n    --quest-ui-obsidian-fracture-lines: ${mask(a)};\n    --quest-ui-obsidian-core-position: ${a.position};\n}`).join("\n")}\n`;
}

const assets = new URL("./assets/", import.meta.url);
const maps = JSON.parse(readFileSync(new URL("manifest.json", assets), "utf8"));
const expected = ["spine", "burst", "edge", "lattice", "shell"];
if (maps.length !== expected.length || maps.some((map, index) => map.name !== expected[index]
    || map.surface !== map.name + "-surface.jpg" || map.mask !== map.name + "-mask.png"
    || !/^\d+% \d+%$/.test(map.position))) {
    throw new Error("Invalid Obsidian material manifest");
}
const generated = managedCSS(maps, name => readFileSync(new URL(name, assets)).toString("base64"));
const destination = new URL("./fracture-assets.css", import.meta.url);
if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== generated) throw new Error("Obsidian texture CSS is out of date");
    console.log("Obsidian authored texture assets: verified");
} else {
    writeFileSync(destination, generated);
}
