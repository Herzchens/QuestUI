// Regenerate managed CSS data URLs without external runtime assets or loaders.
import { readFileSync, writeFileSync } from "node:fs";

const maps = [
    {
        "name": "spine",
        "position": "48.4% 54.1%"
    },
    {
        "name": "burst",
        "position": "60% 50.5%"
    },
    {
        "name": "edge",
        "position": "67.6% 46.8%"
    },
    {
        "name": "lattice",
        "position": "55% 49.1%"
    }
];
const asset = (name, kind) => {
    const svg = readFileSync(new URL(`./assets/${name}-${kind}.svg`, import.meta.url), "utf8");
    return `url("data:image/svg+xml;base64,${Buffer.from(svg.replace(/>\s+</g, "><").trim()).toString("base64")}")`;
};
const root = `/* Generated by generateFractureAssets.mjs from assets/*.svg. Edit the SVG sources. */
.quest-ui-theme-obsidian {
    --quest-ui-obsidian-shell-facets: ${asset("edge", "surface")};
    --quest-ui-obsidian-shell-fissures: ${asset("edge", "mask")};
}
`;
const variants = maps.map(({ name, position }, index) => `.quest-ui-theme-obsidian .quest-ui-card[data-obsidian-fracture="${index}"] {
    --quest-ui-obsidian-fracture-facets: ${index === 2 ? "var(--quest-ui-obsidian-shell-facets)" : asset(name, "surface")};
    --quest-ui-obsidian-fracture-lines: ${index === 2 ? "var(--quest-ui-obsidian-shell-fissures)" : asset(name, "mask")};
    --quest-ui-obsidian-core-position: ${position};
}`).join("\n");
writeFileSync(new URL("./fracture-assets.css", import.meta.url), root + variants + "\n");
